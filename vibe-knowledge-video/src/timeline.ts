// src/timeline.ts — single source of truth: every scene cut lands on a downbeat.
import beats from "./beats"; // generated by scripts/prepare.py

export const FPS: number = beats.fps;
export const DOWN: number[] = beats.downbeat_frames;          // 重拍帧号
export const BEAT: number[] = beats.beat_frames;
export const AUDIO: string = beats.audio;                     // file in public/

export type SceneSpec = {
  id: string; bars: number; caption?: string;
  sfx?: { at: number; name: string; volume?: number }[]; // at = frames from scene start
};
export type Scene = SceneSpec & { from: number; duration: number; startDown: number };

// Lay scenes end-to-end on the downbeat grid. `bars` = how many downbeats a scene lasts.
export function layout(specs: SceneSpec[], firstDown = 0): Scene[] {
  let d = firstDown;
  const out: Scene[] = [];
  for (const s of specs) {
    const end = d + s.bars;
    if (end >= DOWN.length) throw new Error(`Scene ${s.id} runs past the music (needs downbeat #${end}, track has ${DOWN.length - 1}). Use fewer bars or a longer track.`);
    // first scene starts at frame 0 (covers the pickup before the first downbeat) -> no black lead-in
    const from = out.length === 0 ? 0 : DOWN[d];
    out.push({ ...s, from, duration: DOWN[end] - from, startDown: d });
    d = end;
  }
  return out;
}

// Beats (not downbeats) inside a scene, relative to its start — for in-scene key actions.
export function beatsIn(scene: Scene): number[] {
  return BEAT.filter((f) => f >= scene.from && f < scene.from + scene.duration).map((f) => f - scene.from);
}

// Frame range of the k-th ~10 s trial segment, snapped to downbeats (for `--frames=a-b`).
export function trialRange(scenes: Scene[], k: number, seconds = 10): [number, number] {
  const cuts = [scenes[0].from, ...scenes.map((s) => s.from + s.duration)];
  const target = seconds * FPS;
  const segs: [number, number][] = [];
  let a = cuts[0];
  for (let i = 1; i < cuts.length; i++) {
    if (cuts[i] - a >= target || i === cuts.length - 1) { segs.push([a, cuts[i] - 1]); a = cuts[i]; }
  }
  if (k >= segs.length) throw new Error(`only ${segs.length} trial segments`);
  return segs[k];
}
