#!/usr/bin/env python3
"""One step: find the music in public/, detect beats -> src/beats.ts, synthesize SFX -> public/sfx/.
Usage (from project root):  python scripts/prepare.py [--bpm-hint 120] [--key C]
Uses public/music.{mp3,flac,wav,m4a,ogg} if present, otherwise public/placeholder.wav.
If public/music.grid.json exists (written by compose.py), the exact composed beat grid is used instead of detection.
"""
import argparse, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB, SCRIPTS = os.path.join(ROOT, "public"), os.path.join(ROOT, "scripts")

ap = argparse.ArgumentParser()
ap.add_argument("--bpm-hint"); ap.add_argument("--key", default="C"); ap.add_argument("--meter", default="4"); ap.add_argument("--phase")
a = ap.parse_args()

audio = next((f"music.{e}" for e in ["mp3", "flac", "wav", "m4a", "ogg"] if os.path.exists(os.path.join(PUB, f"music.{e}"))),
             "placeholder.wav")
grid_path = os.path.join(PUB, os.path.splitext(audio)[0] + ".grid.json")
if os.path.exists(grid_path):
    # music composed by compose.py: the beat grid is exact, skip detection
    g = json.load(open(grid_path)); beat = 60 / g["bpm"]; m = int(g["meter"]); off = g.get("offset_s", 0.0)
    times = [round(off + k * beat, 3) for k in range(g["bars"] * m + 1)]
    data = {"duration_s": round(times[-1], 3), "fps": 30, "bpm": g["bpm"], "beat_interval_s": round(beat, 4), "meter": m,
            "beats_s": times, "downbeats_s": times[::m], "beat_frames": [round(t * 30) for t in times],
            "downbeat_frames": [round(t * 30) for t in times[::m]], "accents_s": [], "drop_s": g.get("drop_s"), "source": "grid"}
else:
    cmd = [sys.executable, os.path.join(SCRIPTS, "beats.py"), os.path.join(PUB, audio), "--fps", "30", "--meter", a.meter]
    if a.bpm_hint: cmd += ["--bpm-hint", a.bpm_hint]
    if a.phase: cmd += ["--phase", a.phase]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: sys.exit(r.stderr)
    data = json.loads(r.stdout)
data["audio"] = audio
with open(os.path.join(ROOT, "src", "beats.ts"), "w", encoding="utf-8") as f:
    f.write("// generated by scripts/prepare.py - do not edit\nexport default " + json.dumps(data) + ";\n")
subprocess.run([sys.executable, os.path.join(SCRIPTS, "sfx.py"), os.path.join(PUB, "sfx"), "--key", a.key], check=True,
               stdout=subprocess.DEVNULL)
bar = data["beat_interval_s"] * int(a.meter)
print(f"music={audio} ({data.get('source', 'detected')})  BPM={data['bpm']}  bar={bar:.2f}s  downbeats={len(data['downbeats_s'])}  "
      f"first downbeat={data['downbeats_s'][0] if data['downbeats_s'] else '-'}s  -> src/beats.ts, public/sfx/")
